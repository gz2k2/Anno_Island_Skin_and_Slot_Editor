# Exact normalized path -> category index. Duplicate object paths are rejected.
RD3D_OBJECT_CATEGORY_BY_PATH = {}
for _category, _objects in RD3D_CATEGORIES.items():
    for _object_path in _objects:
        _normalized = str(_object_path).strip().replace("\\", "/").casefold()
        if not _normalized:
            continue
        _previous = RD3D_OBJECT_CATEGORY_BY_PATH.get(_normalized)
        if _previous is not None and _previous != _category:
            raise ValueError(
                f"RD3D object path is assigned to multiple categories: "
                f"{_object_path!r} ({_previous!r}, {_category!r})"
            )
        RD3D_OBJECT_CATEGORY_BY_PATH[_normalized] = _category

